// between XO and the library. Design: design-research/2026-11-vision/pierre/README.md.
//
// Nothing loads until it's needed: the library (≈400 KB, then a chunk per language) is fetched by
// prefetch() when the browser is truly idle in a place that has changes, or by the first draw. A diff is
// drawn from git's patch (hunks only), never from two whole files.
//
// All colouring happens in one module worker: the page draws the rows at once and the colour follows a
// moment later. A grammar compiles its patterns on first use, which is most of a cold draw (measured on the
// page: one 300 ms task opening the panel, 50–110 ms tasks warming at idle); in the worker none of it is the
// page's. So nothing here ever freezes the conversation, warm or cold.
//
// The look: the syntax colours are XO's code tokens as a TextMate pair (js/diffthemes.js, generated by
// tools/diffview/theme.mjs); everything else is CSS custom properties on the library's element
// (css/diffs.css), so light and dark switch without a redraw. app.js calls setTheme() when you switch.
//
// Calls: ready, prefetch, diff, file (with edit), conflict, jump, langOf, setTheme, loaded.

