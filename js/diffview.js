/** The highlighting language for a path, or "text". */
export function langOf(path) {
  const name = String(path || "").split("/").pop().toLowerCase();
  if (NAME[name]) return NAME[name];
  if (name.startsWith(".env.")) return "dotenv";
  if (name.startsWith("dockerfile.")) return "docker";
  const dot = name.lastIndexOf(".");
  return (dot > 0 || (dot === 0 && name.length > 1)) ? EXT[name.slice(dot + 1)] || "text" : "text";
}

// ── the library, on first need ─────────────────────────────────────────────────
let lib = null;
function load() {
  lib ??= Promise.all([import(LIB), import("./diffthemes.js")]).then(([P, T]) => {
    P.registerCustomTheme("xo-dark", async () => T.XO_DARK);
    P.registerCustomTheme("xo-light", async () => T.XO_LIGHT);
    return P;
  }).catch((e) => { lib = null; throw e; }); // a failed fetch can be tried again
  return lib;
}
let pool = null;
function workers(P) {
  pool ??= P.getOrCreateWorkerPoolSingleton({
    poolOptions: { workerFactory: () => new Worker(WORKER, { type: "module" }), poolSize: 1, mainThreadMaxCharacters: MAIN_MAX },
    highlighterOptions: { theme: THEMES, langs: [], preferredHighlighter: "shiki-js" },
  });
  return pool;
}

/** Is the library here already (so a draw is quick)? */
export const loaded = () => !!lib;

/**
 * Get the first draw ready while the browser is idle: the library, each language's grammar, and the
 * grammar's patterns compiled by colouring a sample of the very text that will be drawn (a grammar compiles
 * its patterns on first use, which is most of a cold draw: ≈190 ms against ≈20 ms warm). items: paths, or
 * {path, patch} (git's patch for it). Safe to call often: each language warms once a session.
 */
const warmed = new Set();
const idle = () => new Promise((r) => (typeof requestIdleCallback === "function" ? requestIdleCallback(r, { timeout: 2000 }) : setTimeout(() => r({ timeRemaining: () => 8 }), 16)));
export function prefetch(items = [], { now = false } = {}) {
  const want = new Map();
  for (const it of items) {
    const path = typeof it === "string" ? it : it.path, lang = langOf(path);
    if (lang !== "text" && !warmed.has(lang) && !want.get(lang)) want.set(lang, typeof it === "string" ? null : it.patch || null);
  }
  if (lib && !want.size) return;
  for (const l of want.keys()) warmed.add(l);
  (async () => {
    if (!now) await idle();
    const P = await load();
    const h = await P.getSharedHighlighter({ themes: [THEMES.dark, THEMES.light], langs: [...want.keys()], preferredHighlighter: "shiki-js" });
    for (const [lang, patch] of want) {
      // the patch's own lines, without their +/−/space column, a few at a time between frames
      const lines = String(patch || "").split("\n").filter((l) => /^[ +-]/.test(l) && !/^(\+\+\+|---) /.test(l)).map((l) => l.slice(1)).slice(0, 160);
      for (let i = 0; i < lines.length;) {
        const d = await idle();
        do { h.codeToTokens(lines.slice(i, i + 4).join("\n"), { lang, theme: THEMES.dark }); i += 4; } while (i < lines.length && d.timeRemaining() > 8);
      }
    }
  })().catch(() => { for (const l of want.keys()) warmed.delete(l); });
}

// ── the theme: every live view follows the app's switch ─────────────────────────────
const live = new Set();
const themeNow = () => (document.documentElement.dataset.theme === "light" ? "light" : "dark");
export function setTheme(t) { for (const v of live) v.setThemeType(t); }

const common = (o) => ({
  theme: THEMES, themeType: themeNow(), preferredHighlighter: "shiki-js",
  disableFileHeader: true, overflow: o.wrap ? "wrap" : "scroll", tokenizeMaxLineLength: 1000,
});

/** One file's diff out of git's patch for it (its whole `diff --git` block). */
function parse(P, patch, path, key) {
  const fd = P.parsePatchFiles(patch, key ? { cacheKeyPrefix: key } : undefined)[0]?.files[0];
  if (!fd) throw new Error("not a patch");
  fd.lang = langOf(path || fd.name);
  return fd;
}

/**
 * A diff into host, from git's patch. o: {path, wrap, split, key (a cache key for this version),
 * loadFiles(fileDiff) → {oldFile, newFile} (both sides whole: "N unmodified lines" can then unfold),
 * onSelect(range)}. Resolves to {update(patch, key), split(on), destroy()}.
 */
export async function diff(host, patch, o = {}) {
  const P = await load();
  const v = new P.FileDiff({
    ...common(o), diffStyle: o.split ? "split" : "unified", diffIndicators: "bars", lineDiffType: "word",
    hunkSeparators: "line-info", expansionLineCount: 20,
    ...(o.loadFiles ? { loadDiffFiles: (fd) => o.loadFiles(fd) } : {}),
    ...(o.onSelect ? { enableLineSelection: true, onLineSelected: o.onSelect } : {}),
  });
  v.render({ fileDiff: parse(P, patch, o.path, o.key), containerWrapper: host });
  live.add(v);
  return {
    update(next, key) { v.render({ fileDiff: parse(P, next, o.path, key), containerWrapper: host }); },
    split(on) { v.setOptions({ ...v.options, diffStyle: on ? "split" : "unified" }); v.rerender(); },
    destroy() { live.delete(v); v.cleanUp(); host.replaceChildren(); },
  };
}

/**
 * A whole file into host. o: {path, wrap, key, onSelect(range)}. Big files colour in a worker; huge
 * ones stay plain. Resolves to {select(range), destroy()}.
 */
export async function file(host, contents, o = {}) {
  const P = await load();
  const lang = contents.length > PLAIN_OVER ? "text" : langOf(o.path);
  const v = new P.File({
    ...common(o),
    ...(o.onSelect ? { enableLineSelection: true, onLineSelected: o.onSelect } : {}),
  }, contents.length > MAIN_MAX && lang !== "text" ? workers(P) : undefined);
  v.render({ file: { name: String(o.path || "").split("/").pop(), contents, lang, ...(o.key ? { cacheKey: o.key } : {}) }, containerWrapper: host });
  live.add(v);
  return {
    select(range) { v.setSelectedLines(range); },
    destroy() { live.delete(v); v.cleanUp(); host.replaceChildren(); },
  };
}
