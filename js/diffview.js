/** The highlighting language for a path, or "text". */
export function langOf(path) {
  const name = String(path || "").split("/").pop().toLowerCase();
  if (NAME[name]) return NAME[name];
  if (name.startsWith(".env.")) return "dotenv";
  if (name.startsWith("dockerfile.")) return "docker";
  const dot = name.lastIndexOf(".");
  return (dot > 0 || (dot === 0 && name.length > 1)) ? EXT[name.slice(dot + 1)] || "text" : "text";
}

// ── the library, on first need ─────────────────────────────────────────────────
let lib = null;
function load() {
  lib ??= Promise.all([import(LIB), import("./diffthemes.js")]).then(([P, T]) => {
    P.registerCustomTheme("xo-dark", async () => T.XO_DARK);
    P.registerCustomTheme("xo-light", async () => T.XO_LIGHT);
    return P;
  }).catch((e) => { lib = null; throw e; }); // a failed fetch can be tried again
  return lib;
}
let pool = null;
function workers(P) {
  pool ??= P.getOrCreateWorkerPoolSingleton({
    poolOptions: { workerFactory: () => new Worker(WORKER, { type: "module" }), poolSize: 1, mainThreadMaxCharacters: 0 },
    highlighterOptions: { theme: THEMES, langs: [], preferredHighlighter: "shiki-js" },
  });
  return pool;
}

/** Is the library here already (so a draw is quick)? */
export const loaded = () => !!lib;

/**
 * Get the first draw ready when you've stopped touching the page for a moment (no scroll, key or press for
 * 1.2 s, then an idle callback): the library, the worker, and each language's grammar, handed to the worker.
 * A fetch and a parse on the page; the compiling is the worker's. Safe to call often. (The page is rarely
 * idle in the browser's own sense: a busy project's mark animates, so idle deadlines stay at one frame.)
 */
const loadedLangs = new Set();
const INPUT = ["wheel", "scroll", "pointerdown", "keydown", "touchstart"];
const quiet = () => new Promise((r) => {
  if (typeof addEventListener !== "function") { r(); return; }
  let last = performance.now();
  const seen = () => { last = performance.now(); };
  for (const ev of INPUT) addEventListener(ev, seen, { capture: true, passive: true });
  const done = () => { for (const ev of INPUT) removeEventListener(ev, seen, { capture: true }); r(); };
  const check = () => (performance.now() - last >= 1200 ? (typeof requestIdleCallback === "function" ? requestIdleCallback(done, { timeout: 1000 }) : done()) : setTimeout(check, 1200 - (performance.now() - last)));
  setTimeout(check, 1200);
});
/** Files opened: you're about to read a file, so the library and its worker start now (≈25 ms on the page),
 *  not on your first click (≈370 ms then). */
export function ready() {
  if (typeof Worker !== "function") return;
  load().then((P) => workers(P)).catch(() => {});
}
export function prefetch(paths = []) {
  if (typeof Worker !== "function") return; // nowhere to colour (a test, an old browser): the first draw loads it
  const langs = [...new Set(paths.map(langOf))].filter((l) => l !== "text" && !loadedLangs.has(l));
  if (lib && !langs.length) return;
  for (const l of langs) loadedLangs.add(l);
  (async () => { await quiet(); await workers(await load()).initialize(langs); })().catch(() => { for (const l of langs) loadedLangs.delete(l); });
}

