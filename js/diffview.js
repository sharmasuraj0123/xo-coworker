// Diffs and files, drawn by @pierre/diffs (js/vendor/pierre-diffs, vendored at 1.6.4): the one adapter
// between XO and the library. Design: design-research/2026-11-vision/pierre/README.md.
//
// Nothing loads until it's needed: the library (≈400 KB, then a chunk per language) is fetched by
// prefetch() when the browser is idle in a place that has changes, or by the first draw. A diff is drawn
// from git's patch (hunks only, ~20 ms even for a 3,000-line file), never from two whole files. A whole
// file of more than MAIN_MAX characters is coloured in a worker: its rows show at once, colour follows.
//
// The look: the syntax colours are XO's code tokens as a TextMate pair (js/diffthemes.js, generated by
// tools/diffview/theme.mjs); everything else is CSS custom properties on the library's element
// (css/diffs.css), so light and dark switch without a redraw. app.js calls setTheme() when you switch.
//
// Calls: prefetch, diff, file, langOf, setTheme, loaded.

const LIB = new URL("./vendor/pierre-diffs/diffs.js", import.meta.url).href;
const WORKER = new URL("./vendor/pierre-diffs/worker.js", import.meta.url).href;
const THEMES = { dark: "xo-dark", light: "xo-light" };
const MAIN_MAX = 12000;   // characters: a file up to here (≈300 lines) colours faster on the page than via a worker
const PLAIN_OVER = 262144; // a file over 256 KB stays plain text: colouring it would cost more than reading it

// ── languages: what the vendored build carries (tools/diffview/vendor.mjs LANGS) ─────────────
